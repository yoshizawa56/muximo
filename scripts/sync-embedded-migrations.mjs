#!/usr/bin/env bun
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsRoot = join(repositoryRoot, "packages", "infrastructure", "drizzle");
const journalPath = join(migrationsRoot, "meta", "_journal.json");
const journal = JSON.parse(readFileSync(journalPath, "utf8"));
const files = [
  { path: "meta/_journal.json", contents: readFileSync(journalPath, "utf8") },
  ...journal.entries.map((entry) => ({
    path: `${entry.tag}.sql`,
    contents: readFileSync(join(migrationsRoot, `${entry.tag}.sql`), "utf8"),
  })),
];
const outputPath = join(repositoryRoot, "packages", "infrastructure", "src", "persistence", "embedded-migrations.generated.ts");
const output = `// Generated by scripts/sync-embedded-migrations.mjs. Do not edit by hand.\nexport const embeddedMigrationFiles = ${JSON.stringify(files, null, 2)} as const;\n`;
writeFileSync(outputPath, output);
process.stdout.write(`Wrote ${files.length} embedded migration file(s) to ${outputPath}\n`);
